// ethlibFork names the network upgrade EthLib calls each consensus fork.
var ethlibFork = map[string]string{
	"phase0": "phase0", "altair": "altair", "bellatrix": "bellatrix", "capella": "shapella",
	"deneb": "dencun", "electra": "pectra", "fulu": "fusaka", "gloas": "glamsterdam",
}

// knownDivergence lists declarations whose layout differs from EthLib's
// container on purpose of the record: they are proved to differ (a theorem
// `... = false`), so the divergence is machine-checked and cannot vanish or
// spread unnoticed. See formal/README.md, "Findings".
var knownDivergence = map[string]string{
	// Electra+ committee_bits: Bitvector[MAX_COMMITTEES_PER_SLOT] in the spec,
	// tagged as a byte vector of MAX_COMMITTEES_PER_SLOT/8 bytes; under the
	// minimal preset (4 committees) the padding bits go unchecked.
	"minimal/electra/Attestation": "committee_bits", "minimal/electra/AggregateAndProof": "committee_bits",
	"minimal/electra/SignedAggregateAndProof": "committee_bits", "minimal/electra/BeaconBlock": "committee_bits",
	"minimal/electra/BeaconBlockBody": "committee_bits", "minimal/electra/SignedBeaconBlock": "committee_bits",
	"minimal/fulu/Attestation": "committee_bits", "minimal/fulu/AggregateAndProof": "committee_bits",
	"minimal/fulu/SignedAggregateAndProof": "committee_bits", "minimal/fulu/BeaconBlock": "committee_bits",
	"minimal/fulu/BeaconBlockBody": "committee_bits", "minimal/fulu/SignedBeaconBlock": "committee_bits",
	"minimal/gloas/Attestation": "committee_bits", "minimal/gloas/AggregateAndProof": "committee_bits",
	"minimal/gloas/SignedAggregateAndProof": "committee_bits", "minimal/gloas/BeaconBlock": "committee_bits",
	"minimal/gloas/BeaconBlockBody": "committee_bits", "minimal/gloas/SignedBeaconBlock": "committee_bits",
}

// ethlibName maps consensus-spec type names EthLib spells differently.
var ethlibName = map[string]string{"Fork": "ForkVersions"}

// TestEthCrossCheckFresh writes formal/spec/SszSpec/EthCross.lean: for every
// certified Ethereum declaration and every (preset, fork) it serves, a
// theorem that its layout equals the layout of EthLib's own typed consensus
// container at that preset and fork — an independent anchor for
// dynamic-ssz's reading of the Go types and their spec-value expressions.
// FORMAL_UPDATE=1 rewrites the file; otherwise it must be fresh.
func TestEthCrossCheckFresh(t *testing.T) {
	type row struct{ thm, decl, term, diverges string }
	var rows []row
	modules := map[string]bool{}
	var unmatched []string
	for _, preset := range presets {
		for _, fork := range ethForks {
			for _, et := range fork.Types {
				name := et.SpecName
				if alt, ok := ethlibName[name]; ok {
					name = alt
				}
				el, ok := ethlibTypes[name]
				if !ok {
					unmatched = append(unmatched, fork.Fork+"/"+et.SpecName)
					continue
				}
				modules[el.Module] = true
				p := "Preset." + preset
				f := "Fork." + ethlibFork[fork.Fork]
				term := name
				switch el.Params {
				case 1:
					term += " " + p
				case 2:
					term += " " + p + " " + f
				case 3:
					term += " " + f
				}
				rows = append(rows, row{
					thm:      fmt.Sprintf("X_%s_%s_%s", preset, fork.Fork, et.SpecName),
					decl:     "D_" + ethCertName(preset, et.GoName),
					term:     term,
					diverges: knownDivergence[preset+"/"+fork.Fork+"/"+et.SpecName],
				})
			}
		}
	}
	mods := make([]string, 0, len(modules))
	for m := range modules {
		mods = append(mods, m)
	}
	sort.Strings(mods)
	var b strings.Builder
	b.WriteString("import SszSpec.Eth\nimport SszSpec.Layout\n")
	for _, m := range mods {
		b.WriteString("import " + m + "\n")
	}
	b.WriteString(`
/-! Cross-check of the certified Ethereum declarations against EthLib's typed
    consensus containers. Generated by formal/harness (TestEthCrossCheckFresh) — do not edit.

    dynamic-ssz's declaration of each Go type (read from its runtime
    descriptor, spec values of the preset resolved) has the layout of
    EthLib's own definition of that container at that preset and fork: an
    independent anchor for the struct tags and their spec expressions. -/

set_option maxRecDepth 100000

namespace SszSpec

open EthLib.Base EthLib.Consensus EthLib.Serialization.Ssz

`)
	for _, r := range rows {
		if r.diverges != "" {
			fmt.Fprintf(&b, "/-- Known divergence (%s): see formal/README.md, Findings. -/\n", r.diverges)
			fmt.Fprintf(&b, "theorem %s : sameLayout %s (SszType.desc (α := %s)) = false := by decide\n", r.thm, r.decl, r.term)
			continue
		}
		fmt.Fprintf(&b, "theorem %s : sameLayout %s (SszType.desc (α := %s)) = true := by decide\n", r.thm, r.decl, r.term)
	}
	b.WriteString("\nend SszSpec\n")
	path := filepath.Join("..", "spec", "SszSpec", "EthCross.lean")
	if updateCerts {
		if err := os.WriteFile(path, []byte(b.String()), 0o600); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %d cross-check theorems; not in EthLib: %v", len(rows), unmatched)
		return
	}
	got, err := os.ReadFile(path)
	if err != nil || string(got) != b.String() {
		t.Errorf("%s is stale (regenerate with FORMAL_UPDATE=1 go test -run TestEthCrossCheckFresh)", path)
	}
}
