package harness

import (
	"os"
	"os/exec"
	"path/filepath"
	"reflect"
	"testing"

	dynssz "github.com/pk910/dynamic-ssz"
	"github.com/pk910/dynamic-ssz/codegen"
	"github.com/pk910/dynamic-ssz/formal/harness/apigen"
)

// TestCodegenAPI drives the code generator's programmatic API (reflect-typed
// and go/types-typed entry points, every option) and dynssz-gen's
// configuration file over the apigen types, and type-checks what they emit
// (`go vet` of the package). The CLI flags are exercised by the corpus; these
// are the remaining ways in.
func TestCodegenAPI(t *testing.T) {
	goBin, err := exec.LookPath("go")
	if err != nil {
		t.Skip("go not on PATH")
	}
	dir := "apigen"
	vet := func(t *testing.T, what string) {
		t.Helper()
		cmd := exec.Command(goBin, "vet", "./"+dir+"/")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Errorf("%s: generated code does not type-check: %v\n%s", what, err, out)
		}
	}
	clean := func() {
		for _, f := range []string{"api_gen.go", "api_views_gen.go", "config_gen.go", "config_views_gen.go", "gen.yaml"} {
			_ = os.Remove(filepath.Join(dir, f))
		}
	}
	clean()
	t.Cleanup(clean)
	tc := dynssz.NewDynSsz(map[string]any{"SPEC_A": uint64(6)}, dynssz.WithExtendedTypes()).GetTypeCache()

	t.Run("reflect-api", func(t *testing.T) {
		cg := codegen.NewCodeGenerator(tc)
		if err := cg.SetPackageName("apigen"); err != nil {
			t.Fatal(err)
		}
		if err := cg.SetHeaderTemplate("// Code generated by TestCodegenAPI ({version}, {hash}); DO NOT EDIT.\n"); err != nil {
			t.Fatal(err)
		}
		cg.BuildFile(filepath.Join(dir, "api_gen.go"),
			codegen.WithReflectType(reflect.TypeOf(apigen.Inner{}), codegen.WithNoFastSsz()),
			codegen.WithReflectType(reflect.TypeOf(apigen.Outer{}),
				codegen.WithCreateEncoderFn(), codegen.WithCreateDecoderFn(), codegen.WithCreateLegacyFn(),
				codegen.WithReflectViewTypes(reflect.TypeOf(apigen.OuterView{}))),
			codegen.WithReflectType(reflect.TypeOf(apigen.Ext{}), codegen.WithExtendedTypes(), codegen.WithNoHashTreeRoot()),
			codegen.WithReflectType(reflect.TypeOf(apigen.Rec{}), codegen.WithRecursionDepth(16), codegen.WithNoSizeSSZ()),
		)
		if err := cg.Generate(); err != nil {
			t.Fatalf("generate: %v", err)
		}
		vet(t, "reflect API")
		if files, err := cg.GenerateToMap(); err != nil || len(files) == 0 {
			t.Errorf("GenerateToMap: %d files, %v", len(files), err)
		}
		_ = os.Remove(filepath.Join(dir, "api_gen.go"))
	})

	t.Run("reflect-api-partial", func(t *testing.T) {
		// Every piece switched off but one, frozen spec values, view-only.
		cg := codegen.NewCodeGenerator(tc)
		cg.BuildFile(filepath.Join(dir, "api_gen.go"),
			codegen.WithReflectType(reflect.TypeOf(apigen.Inner{}), codegen.WithNoMarshalSSZ(), codegen.WithNoUnmarshalSSZ(), codegen.WithNoSizeSSZ()),
			codegen.WithReflectType(reflect.TypeOf(apigen.Outer{}), codegen.WithoutDynamicExpressions()),
		)
		if err := cg.Generate(); err != nil {
			t.Fatalf("generate: %v", err)
		}
		// View-only generation is a second run over a type that has its
		// methods already (a type is generated into one file per run).
		cg2 := codegen.NewCodeGenerator(tc)
		cg2.BuildFile(filepath.Join(dir, "api_views_gen.go"),
			codegen.WithReflectType(reflect.TypeOf(apigen.Outer{}), codegen.WithViewOnly(),
				codegen.WithReflectViewTypes(reflect.TypeOf(apigen.OuterView{}))),
		)
		if err := cg2.Generate(); err != nil {
			t.Fatalf("generate (view-only): %v", err)
		}
		vet(t, "reflect API, partial")
		_ = os.Remove(filepath.Join(dir, "api_gen.go"))
		_ = os.Remove(filepath.Join(dir, "api_views_gen.go"))
	})

	t.Run("config-file", func(t *testing.T) {
		cfg := `package: .
output: config_gen.go
header: |
  // Code generated by TestCodegenAPI via config; DO NOT EDIT.
with-streaming: true
with-extended-types: true
recursion-depth: 32
types:
  - name: Inner
    legacy: true
  - name: Outer
    views: [OuterView]
    skip-encoder: true
  - name: Ext
    skip-hashtreeroot: true
    without-dynamic-expressions: true
  - name: Rec
    skip-decoder: true
`
		if err := os.WriteFile(filepath.Join(dir, "gen.yaml"), []byte(cfg), 0o600); err != nil {
			t.Fatal(err)
		}
		cmd := exec.Command(goBin, "run", "github.com/pk910/dynamic-ssz/dynssz-gen", "-config", filepath.Join(dir, "gen.yaml"), "-v")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("dynssz-gen -config: %v\n%s", err, out)
		}
		vet(t, "config file")
	})
}
