#!/usr/bin/env python3
"""Regenerates ethlib_types.go: the consensus containers EthLib declares (at
the revision formal/spec pins) with the parameters they take, read from the
EthLib sources lake fetched into formal/spec/.lake/packages/EthLib.

Run from formal/harness after `lake build` in formal/spec:
python3 gen_ethlib_types.py
"""
import glob
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..", "spec", ".lake", "packages", "EthLib", "EthLib", "Consensus")
decl = re.compile(r"^(?:structure|abbrev|def|inductive) ([A-Z][A-Za-z0-9]*)\b(.*)$")
mods = {}
for path in sorted(glob.glob(os.path.join(root, "**", "*.lean"), recursive=True)):
    mod = os.path.relpath(path, os.path.join(root, "..", "..")).replace(os.sep, ".")[:-5]
    text = open(path).read()
    if "SszType" not in text:
        continue
    for line in text.splitlines():
        m = decl.match(line)
        if not m:
            continue
        head = m.group(2).split(" where")[0].split(":=")[0]
        params = 0
        if "preset : Preset" in head:
            params = 1
        if "fork : Fork" in head:
            params = 2 if params == 1 else 3
        mods.setdefault(m.group(1), (mod, params))
out = ["// Code generated by formal/harness/gen_ethlib_types.py from EthLib; DO NOT EDIT.", "",
       "package harness", "",
       "// ethlibTypes maps EthLib's consensus type names to their module and",
       "// parameters (0: none, 1: preset, 2: preset and fork, 3: fork).",
       "var ethlibTypes = map[string]struct {", "\tModule string", "\tParams int", "}{"]
for name in sorted(mods):
    mod, p = mods[name]
    out.append(f'\t"{name}": {{"{mod}", {p}}},')
out += ["}", ""]
open(os.path.join(here, "ethlib_types.go"), "w").write("\n".join(out))
print(len(mods), "types")
import subprocess
subprocess.run(["gofmt", "-w", os.path.join(here, "ethlib_types.go")], check=True)
