#!/usr/bin/env python3
"""Regenerates eth_registry.go from the fork/type tables of tests/spectests.

Run from formal/harness: python3 gen_eth_registry.py
"""
import collections
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
spectests = os.path.join(here, "..", "..", "tests", "spectests")
forks = collections.OrderedDict()
for f in ["phase0", "altair", "bellatrix", "capella", "deneb", "electra", "fulu", "gloas"]:
    src = open(os.path.join(spectests, f"spectests_{f}_test.go")).read()
    forks[f] = re.findall(
        r'name:\s*"([A-Za-z0-9]+)",\s*\n\s*s:\s*[^\n]*\n\s*s2:\s*&codegen\.([A-Za-z0-9]+)\{\}', src)
types = sorted({g for ps in forks.values() for _, g in ps})
out = ["// Code generated by formal/harness/gen_eth_registry.py from tests/spectests; DO NOT EDIT.", "",
       "package harness", "", 'import "github.com/pk910/dynamic-ssz/spectests/codegen"', "",
       "// ethForks maps each consensus fork to its ssz_static type names and the Go",
       "// types (tests/spectests/codegen) that mirror them.",
       "var ethForks = []struct {", "\tFork  string", "\tTypes []ethType", "}{"]
for f, ps in forks.items():
    out.append(f'\t{{"{f}", []ethType{{')
    for n, g in ps:
        out.append(f'\t\t{{"{n}", "{g}", func() any {{ return new(codegen.{g}) }}}},')
    out.append("\t}},")
out.append("}")
out += ["", "// ethGoTypes lists every distinct Go type once, for certification.", "var ethGoTypes = map[string]func() any{"]
for g in types:
    out.append(f'\t"{g}": func() any {{ return new(codegen.{g}) }},')
out.append("}")
out += ["", "type ethType struct {", "\tSpecName string", "\tGoName   string", "\tNew      func() any", "}", ""]
open(os.path.join(here, "eth_registry.go"), "w").write("\n".join(out))
